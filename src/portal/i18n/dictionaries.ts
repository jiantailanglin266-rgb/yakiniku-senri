/**
 * 言語コード → 辞書。
 *
 * 対応している13言語すべてに辞書があります。ここに無い言語コードが来た場合だけ
 * `getDictionary` が英語へフォールバックします。
 * 言語を追加するときは `Dictionary` 型を満たすオブジェクトを作って登録してください
 * （キーが1つでも欠けると型エラーになるため、翻訳漏れはビルド時に見つかります）。
 */
const dictionaries: Record<string, Dictionary> = {
  ja: ja as unknown as Dictionary,
  en,
  ko,
  "zh-cn": zhCn,
  "zh-tw": zhTw,
  es,
  pt,
  fr,
  de,
  th,
  vi,
  id,
  ar,
};

export function getDictionary(locale: string): Dictionary {
  return dictionaries[locale] ?? dictionaries[fallbackLocale];
}

/** その言語のUI辞書が人手で用意されているか（未整備なら翻訳レイヤーを併用します） */
export function hasAuthoredDictionary(locale: string): boolean {
  return locale in dictionaries;
}

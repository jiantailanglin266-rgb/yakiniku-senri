export const sportsById = new Map(sports.map((sport) => [sport.id, sport]));

export function getSport(id: string | undefined): Sport | undefined {
  if (!id) return undefined;
  return sportsById.get(id);
}

export function getSportBySlug(slug: string): Sport | undefined {
  return sports.find((sport) => sport.slug === slug);
}

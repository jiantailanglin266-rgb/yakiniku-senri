export const teams: Team[] = seeds.map((seed) => ({ ...seed, stamp: editorialStamp }));

export const teamsById = new Map(teams.map((team) => [team.id, team]));

export function getTeam(id: string | undefined): Team | undefined {
  if (!id) return undefined;
  return teamsById.get(id);
}

export function getTeamBySlug(slug: string): Team | undefined {
  return teams.find((team) => team.slug === slug);
}

export function teamsByLeague(leagueId: string): Team[] {
  return teams.filter((team) => team.leagueId === leagueId);
}

export function getVenue(id: string | undefined): Venue | undefined {
  if (!id) return undefined;
  return venuesById.get(id);
}

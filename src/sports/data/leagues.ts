export const leaguesById = new Map(leagues.map((league) => [league.id, league]));

export function getLeague(id: string | undefined): League | undefined {
  if (!id) return undefined;
  return leaguesById.get(id);
}

export function getLeagueBySlug(slug: string): League | undefined {
  return leagues.find((league) => league.slug === slug);
}

export function leaguesBySport(sportId: string): League[] {
  return leagues.filter((league) => league.sportId === sportId);
}

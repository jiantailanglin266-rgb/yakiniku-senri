/** ビルド時に検証します。壊れたデータのまま公開されるのを防ぎます。 */
export const tools: AiTool[] = z.array(toolSchema).parse(rawTools);

export function getTools(): AiTool[] {
  return tools;
}

export function findTool(slug: string): AiTool | undefined {
  return tools.find((tool) => tool.slug === slug);
}

export function getToolsByCategory(categoryId: string): AiTool[] {
  return tools.filter((tool) => tool.categories.includes(categoryId));
}

/** 比較表の初期表示に使う、カテゴリー内の代表ツール。 */
export function getComparisonSet(categoryId: string, limit = 6): AiTool[] {
  return getToolsByCategory(categoryId)
    .slice()
    .sort((a, b) => b.editorPick - a.editorPick || a.name.localeCompare(b.name))
    .slice(0, limit);
}

